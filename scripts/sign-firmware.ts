#!/usr/bin/env node
/**
 * Signed OTA releases (ADR 0006). Runs on Node 24 directly: `node scripts/sign-firmware.ts <command>`.
 *
 *   keygen --out <path>            New ECDSA P-256 key pair. The private key is written to <path>, which must be
 *                                  outside this repository; the public key goes into the firmware
 *                                  (firmware/nabd-node/include/ota_pubkey.h).
 *   sign <bin> --version <x.y.z> --url <https://…> [--notes "…"]
 *                                  Hashes and signs a build. The key comes from NABD_OTA_PRIVATE_KEY (PEM text)
 *                                  or NABD_OTA_KEY_FILE (a path), never from the repo. Writes <bin>.release.json
 *                                  and prints the SQL row for firmware_releases.
 *   verify <bin> <manifest.json>   Checks a build against its manifest with the public key in the firmware,
 *                                  exactly as the device does (SHA-256, then ECDSA over that digest).
 *
 * The device verifies with mbedtls_pk_verify(MBEDTLS_MD_SHA256, sha256(image), sig), and Node's
 * sign('sha256', image) signs sha256(image), so the two agree byte for byte.
 */
import {
  createHash,
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign,
  verify,
} from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PUBKEY_HEADER = resolve(REPO, 'firmware/nabd-node/include/ota_pubkey.h');

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function fail(message: string): never {
  console.error(`sign-firmware: ${message}`);
  process.exit(1);
}

function insideRepo(path: string): boolean {
  // On Windows, relative() across drives returns an absolute path: that is outside too.
  const rel = relative(REPO, resolve(path));
  return rel === '' || (!rel.startsWith('..') && !isAbsolute(rel));
}

function writePublicHeader(publicPem: string) {
  const header = `// Public key for signed OTA updates (ECDSA P-256). Generated by scripts/sign-firmware.ts keygen.
// Only the public half is here; the private key never enters the repository or CI logs.
#pragma once

static const char kOtaPublicKey[] = R"PEM(
${publicPem.trim()}
)PEM";
`;
  writeFileSync(PUBKEY_HEADER, header);
}

function publicKeyFromHeader(): string {
  const text = readFileSync(PUBKEY_HEADER, 'utf8');
  const m = text.match(/-----BEGIN PUBLIC KEY-----[\s\S]+?-----END PUBLIC KEY-----/);
  if (!m) fail(`no public key in ${relative(REPO, PUBKEY_HEADER)}; run keygen first`);
  return m[0];
}

function loadPrivateKey() {
  const pem =
    process.env.NABD_OTA_PRIVATE_KEY ??
    (process.env.NABD_OTA_KEY_FILE ? readFileSync(process.env.NABD_OTA_KEY_FILE, 'utf8') : null);
  if (!pem) fail('set NABD_OTA_PRIVATE_KEY (PEM text) or NABD_OTA_KEY_FILE (path outside the repo)');
  if (process.env.NABD_OTA_KEY_FILE && insideRepo(process.env.NABD_OTA_KEY_FILE))
    fail('the private key must live outside the repo');
  const key = createPrivateKey(pem);
  if (key.asymmetricKeyType !== 'ec' || key.asymmetricKeyDetails?.namedCurve !== 'prime256v1')
    fail('the key must be ECDSA P-256');
  return key;
}

export interface Manifest {
  version: string;
  url: string;
  sha256: string;
  sig: string;
  size: number;
  notes: string | null;
}

export function signImage(
  image: Buffer,
  privateKey: ReturnType<typeof createPrivateKey>,
  version: string,
  url: string,
  notes: string | null,
): Manifest {
  return {
    version,
    url,
    sha256: createHash('sha256').update(image).digest('hex'),
    sig: sign('sha256', image, privateKey).toString('base64'), // DER-encoded ECDSA signature
    size: image.length,
    notes,
  };
}

export function verifyImage(image: Buffer, manifest: Manifest, publicPem: string): string | null {
  if (createHash('sha256').update(image).digest('hex') !== manifest.sha256) return 'sha256 mismatch';
  const ok = verify('sha256', image, createPublicKey(publicPem), Buffer.from(manifest.sig, 'base64'));
  return ok ? null : 'bad signature';
}

const sql = (s: string | null) => (s === null ? 'NULL' : `'${s.replaceAll("'", "''")}'`);

function main() {
  const [command, ...rest] = process.argv.slice(2);
  if (command === 'keygen') {
    const out = arg('out') ?? fail('keygen needs --out <path outside the repo>');
    if (insideRepo(out)) fail('refusing to write a private key inside the repository');
    if (existsSync(out)) fail(`${out} already exists; refusing to overwrite a key`);
    const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
    writeFileSync(out, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
    writePublicHeader(publicKey.export({ type: 'spki', format: 'pem' }).toString());
    console.log(`private key: ${out} (keep it secret; set NABD_OTA_KEY_FILE to it when signing)`);
    console.log(`public key:  ${relative(REPO, PUBKEY_HEADER)} (commit it; rebuild the firmware)`);
    return;
  }
  if (command === 'sign') {
    const bin = rest[0] ?? fail('sign needs the path to the .bin');
    const version = arg('version') ?? fail('sign needs --version x.y.z');
    const url = arg('url') ?? fail('sign needs --url https://…');
    if (!/^\d+\.\d+\.\d+$/.test(version)) fail('version must be x.y.z');
    if (!url.startsWith('https://')) fail('the download URL must be https');
    const image = readFileSync(bin);
    const manifest = signImage(image, loadPrivateKey(), version, url, arg('notes') ?? null);
    // Self-check with the public key that will be compiled into devices.
    const problem = verifyImage(image, manifest, publicKeyFromHeader());
    if (problem) fail(`the signature does not verify with ota_pubkey.h (${problem}); wrong key?`);
    writeFileSync(`${bin}.release.json`, `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(JSON.stringify(manifest, null, 2));
    console.log(
      `\n-- add the release (the API serves it at GET /firmware):\nINSERT INTO firmware_releases (version, sha256, signature, url, notes) VALUES (${sql(manifest.version)}, ${sql(manifest.sha256)}, ${sql(manifest.sig)}, ${sql(manifest.url)}, ${sql(manifest.notes)});`,
    );
    return;
  }
  if (command === 'verify') {
    const [bin, manifestPath] = rest;
    if (!bin || !manifestPath) fail('verify needs <bin> <manifest.json>');
    const problem = verifyImage(
      readFileSync(bin),
      JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest,
      publicKeyFromHeader(),
    );
    if (problem) fail(problem);
    console.log('ok: hash and signature match the firmware public key');
    return;
  }
  fail(
    'usage: sign-firmware.ts keygen --out <path> | sign <bin> --version x.y.z --url https://… | verify <bin> <manifest>',
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
